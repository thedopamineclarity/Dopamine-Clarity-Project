export function isVerifiedCoordinator(user: User | null): boolean {
  if (!user || !user.email || !user.emailVerified) {
    return false;
  }
  return COORDINATOR_EMAILS.includes(user.email.toLowerCase());
}

export async function signInCoordinatorWithGoogle(): Promise<User> {
  const provider = new GoogleAuthProvider();
  provider.setCustomParameters({ prompt: 'select_account' });
  const result = await signInWithPopup(auth, provider);
  return result.user;
}

export async function signOutCoordinator(): Promise<void> {
  await signOut(auth);
}
